export function getLocalizedSubjectName(subjectId: string, fallbackName: string, lang: LanguageCode, subjectMapBn: Record<string, string>): string {
  if (lang === 'bn' && subjectMapBn[subjectId]) {
    return subjectMapBn[subjectId];
  }
  return fallbackName;
}

export function getLocalizedTopic(topic: TopicChapter, lang: LanguageCode): TopicChapter {
  if (lang !== 'bn') return topic;
  const bn = BANGLA_TOPICS[topic.id];
  if (!bn) return topic;
  return {
    ...topic,
    title: bn.title,
    subtitle: bn.subtitle,
    corePrinciple: bn.corePrinciple,
    levels: bn.levels,
    keyTakeaways: bn.keyTakeaways,
    realWorldApplication: bn.realWorldApplication,
  };
}

export function getLocalizedQuestion(q: QuestionEntry, lang: LanguageCode): QuestionEntry {
  if (lang !== 'bn') return q;
  const bn = BANGLA_QUESTIONS[q.id];
  if (!bn) return q;
  return {
    ...q,
    question: bn.question,
    shortAnswer: bn.shortAnswer,
    detailedExplanation: bn.detailedExplanation,
    stepByStep: bn.stepByStep,
    commonMisconception: bn.commonMisconception,
  };
}
